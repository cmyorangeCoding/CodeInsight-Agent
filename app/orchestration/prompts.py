"""编排层各策略使用的系统提示词。

复用仓库分析工具集与工具选择规则，但按策略强调不同的执行方式：
- direct：不做多余交互，一次定位即可回答
- react：多轮检索-观察-再检索
- step：只完成计划中的单个步骤
"""
from app.agents.repository_agent import REPOSITORY_SYSTEM_PROMPT

_TOOL_RULES = REPOSITORY_SYSTEM_PROMPT

DIRECT_PROMPT = (
    _TOOL_RULES
    + """

            【当前模式：Direct 直接回答】
            - 这是一个简单定位型问题，不要做多余的多轮探索。
            - 最多调用 1~2 次工具（优先 search_code_rag 定位，必要时 read_file 精读一次），
              拿到证据后立刻给出简洁答案。
            - 回答必须包含文件路径；能确定行号时必须给出行号。
            - 不要输出任务计划，不要反复检索同一个关键词。
            """
)

REACT_PROMPT = (
    _TOOL_RULES
    + """

            【当前模式：ReAct 多轮工具交互】
            - 观察当前信息 → 选择工具 → 获取结果 → 判断是否继续 → 生成答案。
            - 每轮只根据已有结果决定下一步动作，避免重复调用相同工具与参数。
            - 证据足够后立即收敛并给出答案，不要无意义地扩大检索范围。
            """
)

STEP_PROMPT = (
    _TOOL_RULES
    + """

            【当前模式：计划单步执行】
            - 你只负责完成用户消息中指定的【一个分析步骤】。
            - 预算严格：本步骤最多调用 2~3 次工具。优先按用户消息里给出的
              「已定位证据」直接 read_file 对应位置核对；证据已足够时不要再去检索。
            - 只做完成该步骤所需的检索/读取，不要越界去完成其他步骤。
            - 拿到足够证据后立即输出该步骤的事实性结论（附文件路径与行号），
              不要继续扩大探索范围，不要输出整体最终报告。
            - 若检索不到证据，明确说明「未找到证据」，不要编造。
            """
)
